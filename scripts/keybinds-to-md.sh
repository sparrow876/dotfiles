#!/usr/bin/env bash
# Generate the keybind table (Markdown) from the live Hyprland binds, using
# the same scripts/keybinds.jq as the cheat sheet (ALT + /).
#   keybinds-to-md.sh              print the table
#   keybinds-to-md.sh README.md    replace the part between
#                                  <!-- keybinds:start --> and <!-- keybinds:end -->
# Needs a running Hyprland (reads `hyprctl binds -j`).
set -euo pipefail
dir="$(cd "$(dirname "$0")" && pwd)"

table=$(hyprctl binds -j | jq -r -f "$dir/keybinds.jq" | jq -r '
  .[] |
  "### \(.category)\n",
  "| Keys | Action |",
  "|------|--------|",
  # inline code; a key containing ` needs double-backtick code spans
  (.items[] | "| \(.keys | map(if test("`") then "`` " + . + " ``" else "`" + . + "`" end) | join(" / ")) | \(.action) |"),
  ""')

if [[ $# -eq 0 ]]; then
  printf '%s\n' "$table"
  exit 0
fi

file=$1
grep -q '<!-- keybinds:start -->' "$file" && grep -q '<!-- keybinds:end -->' "$file" ||
  { echo "$file has no <!-- keybinds:start --> / <!-- keybinds:end --> markers" >&2; exit 1; }
tmp=$(mktemp)
TABLE="$table" awk '
  /<!-- keybinds:start -->/ { print; print "<!-- generated by scripts/keybinds-to-md.sh; do not edit by hand -->"; print ""; print ENVIRON["TABLE"]; skip=1; next }
  /<!-- keybinds:end -->/   { skip=0 }
  !skip' "$file" > "$tmp"
mv "$tmp" "$file"
echo "Updated the keybind table in $file"
